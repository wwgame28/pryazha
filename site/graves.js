// n могил; risen — номера могил, из которых встали мертвецы; old — Старое кладбище, где все имена сбиты.
// Возвращает надпись для каждой могилы: {name, female, role, line, mutter, intact, risen}.
export function planYard(key, n, risen = [], { old = false, spare = 2 } = {}) {
  const h = (...a) => hash01('yard', key, ...a);
  const shuffle = (arr, salt) => arr.map((v, i) => [h(salt, i), v]).sort((a, b) => a[0] - b[0]).map((p) => p[1]);
  const idx = [...Array(n).keys()];
  const intact = new Set(old ? [] : risen.filter((i) => i >= 0 && i < n));
  // ещё пара целых имён — непроводенные, что лежат спокойно: по ним мертвеца не узнать, можно ошибиться
  if (!old) for (const i of shuffle(idx.filter((i) => !intact.has(i)), 'spare').slice(0, spare)) intact.add(i);
  // ремёсла и имена не повторяются: сначала раздаём целым могилам, потом остальным
  const roles = shuffle(ROLES, 'role'), men = shuffle(MALE, 'm'), women = shuffle(FEMALE, 'w');
  const order = [...idx.filter((i) => intact.has(i)), ...idx.filter((i) => !intact.has(i))];
  const out = new Array(n); let mi = 0, wi = 0;
  order.forEach((i, k) => {
    const r = roles[k % roles.length], female = !r.m ? true : !r.f ? false : h('sex', i) < .5;
    const name = female ? women[wi++ % women.length] : men[mi++ % men.length];
    out[i] = { name, female, role: female ? r.f : r.m, line: r.line, mutter: r.mutter, intact: intact.has(i), risen: !old && risen.includes(i) };
  });
  return out;
}

